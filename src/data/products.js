/** Returns products filtered by category id. */
export function getByCategory(categoryId) {
  return PRODUCTS.filter(p => p.category === categoryId);
}

/** Returns products filtered by brand name. */
export function getByBrand(brand) {
  return PRODUCTS.filter(p => p.brand === brand);
}

/** Returns a single product by id. */
export function getById(id) {
  return PRODUCTS.find(p => p.id === id) ?? null;
}

/** Simple text search across name, brand, description, and tags. */
export function searchProducts(query) {
  const q = query.toLowerCase().trim();
  if (!q) return PRODUCTS;
  return PRODUCTS.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.brand.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.tags.some(t => t.includes(q))
  );
}

/** Format price in CLP. */
export function formatPrice(price, currency = 'CLP') {
  if (currency === 'CLP') return `$${price.toLocaleString('es-CL')}`;
  return `${currency} ${price.toLocaleString()}`;
}
